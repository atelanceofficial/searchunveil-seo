import { lensRings } from './lens.ts';

/**
 * The pattern files under src/assets/patterns, as text. `npm run patterns` writes them and a
 * test checks that the committed files match, so they can always be rebuilt from this source.
 *
 * The files are drawn in black and used as CSS masks: the interface paints them with its own
 * color tokens, so one file serves both themes, high contrast and right-to-left layouts.
 */

const NOTICE = '<!-- Generated by scripts/generate-patterns.ts from apps/web/src/patterns. -->';

/** The lens motif, engraved into the footer. */
export function lensPatternSvg(): string {
  const width = 1000;
  const height = 700;
  const rings = lensRings({ rings: 30, samples: 36, width, height, padding: 6, phase: 0.9 });
  const paths = rings
    .map((ring) => {
      const opacity = (0.28 + 0.72 * ring.glow).toFixed(2);
      const weight = ring.accent ? ' stroke-width="2.4"' : '';
      return `<path d="${ring.d}" stroke-opacity="${opacity}"${weight}/>`;
    })
    .join('\n');
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${String(width)}" height="${String(height)}" viewBox="0 0 ${String(width)} ${String(height)}">`,
    NOTICE,
    '<g fill="none" stroke="#000" stroke-width="1.4" stroke-linejoin="round">',
    paths,
    '</g>',
    '</svg>',
    '',
  ].join('\n');
}

export const PATTERN_FILES: Readonly<Record<string, () => string>> = {
  'lens.svg': lensPatternSvg,
};
